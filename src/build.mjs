// Static site build. No dependencies — run with `node src/build.mjs`.
//
// Reads the page modules and case-study content, writes plain HTML files into
// the repository root (which GitHub Pages serves as-is), concatenates the CSS,
// and regenerates sitemap.xml, robots.txt, the legacy redirects and
// CONTENT-NEEDED.md.

import { writeFileSync, mkdirSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { site } from './site.mjs';
import { documentShell, placeholderLog } from './layout.mjs';
import { renderCase } from './case.mjs';
import { projects } from './content/projects.mjs';

import home from './pages/home.mjs';
import about from './pages/about.mjs';
import contact from './pages/contact.mjs';
import notfound from './pages/notfound.mjs';
import managem from './content/case-managem.mjs';
import wastemart from './content/case-wastemart.mjs';
import gemis from './content/case-gemis.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = (rel, content) => {
  const file = join(root, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
};
const depthOf = (path) => path.split('/').length - 1;

// ------------------------------------------------------------------ pages

const caseContent = { managem, wastemart, gemis };
const casePages = projects.map((p) => ({
  path: `work/${p.slug}/index.html`,
  page: p.name,
  navKey: 'work',
  slug: p.slug,
  title: `${p.name} — Case study`,
  description: p.description,
  bodyClass: `page-case page-case--${p.slug}`,
  ogImage: undefined,
  render: (ctx) => renderCase(ctx, caseContent[p.slug]),
}));

const pages = [home, ...casePages, about, contact, notfound];

for (const p of pages) {
  const ctx = { path: p.path, depth: depthOf(p.path), page: p.page, navKey: p.navKey, slug: p.slug, absolute: p.path === '404.html' };
  const body = p.render(ctx);
  const opts = { title: p.title, description: p.description, body, bodyClass: p.bodyClass, noindex: p.noindex };
  if (p.ogImage) opts.ogImage = p.ogImage;
  out(p.path, documentShell(ctx, opts));
}

// --------------------------------------------------------------------- css

const styleDir = join(root, 'src/styles');
const css = readdirSync(styleDir)
  .filter((f) => f.endsWith('.css'))
  .sort()
  .map((f) => `/* ${f} */\n${readFileSync(join(styleDir, f), 'utf8')}`)
  .join('\n');
out('assets/css/site.css', `/* Built from src/styles — edit those files, then run: node src/build.mjs */\n${css}`);

// ------------------------------------------------------- sitemap & robots

const today = new Date().toISOString().slice(0, 10);
const indexable = pages.filter((p) => !p.noindex);
out(
  'sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${indexable
  .map((p) => `  <url><loc>${site.origin}${site.basePath}${p.path.replace(/index\.html$/, '')}</loc><lastmod>${today}</lastmod></url>`)
  .join('\n')}
</urlset>
`,
);
out(
  'robots.txt',
  `# On a GitHub Pages project site this file is not at the host root, so
# crawlers will not read it. It applies as-is if the site moves to its own domain.
User-agent: *
Allow: /
Sitemap: ${site.origin}${site.basePath}sitemap.xml
`,
);

// --------------------------------------------- redirects from the old site

const legacy = {
  'managem.html': 'work/managem/',
  'wastemart.html': 'work/wastemart/',
  'gemis-studio.html': 'https://sphamandla-designer.github.io/gemis-site/studio/',
  'wastemart-proto.html': 'prototypes/wastemart.html',
  'ManaGem.html': 'prototypes/managem.html',
};
for (const [from, to] of Object.entries(legacy)) {
  const target = /^https?:/.test(to) ? to : '../'.repeat(depthOf(from)) + to;
  out(
    from,
    `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Moved</title><meta name="robots" content="noindex"><meta http-equiv="refresh" content="0; url=${target}"><link rel="canonical" href="${target}"></head><body><p>This page has moved: <a href="${target}">${target}</a></p></body></html>\n`,
  );
}

// ------------------------------------------------- content still needed

const byPage = {};
for (const ph of placeholderLog) (byPage[ph.page] ||= []).push(ph);
const md = [
  '# Content still needed',
  '',
  'Generated by `node src/build.mjs` from every placeholder on the site. Each item',
  'is visible on the page as a dashed “Placeholder — content needed” box, so',
  'nothing missing is presented as fact. Supply the item, replace the',
  '`placeholder(...)` / `phInline(...)` call in `src/content/`, and rebuild.',
  '',
  ...Object.entries(byPage).flatMap(([page, items]) => [
    `## ${page}`,
    '',
    ...items.map((i) => `- [ ] **${i.need}**${i.detail ? ` ${i.detail}` : ''}`),
    '',
  ]),
].join('\n');
out('CONTENT-NEEDED.md', md);

console.log(`Built ${pages.length} pages, ${Object.keys(legacy).length} redirects, ${placeholderLog.length} placeholders logged.`);
